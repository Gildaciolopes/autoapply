import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { chromium, type Browser } from 'playwright';
import { normalizeQuestion } from '@autoapply/apply';
import { closeRenderer } from '@autoapply/resume';
import { runApply } from '../src/apply/run.js';
import type { FixtureServer } from '../src/apply/browser.js';
import { db } from './helpers.js';
import { resetAll } from './jobs-helpers.js';
import { applyDeps, applyLlm, seedApplyPersona } from './apply-helpers.js';

let browser: Browser;
beforeAll(async () => {
  browser = await chromium.launch({ headless: true });
});
afterAll(async () => {
  await browser.close();
  await closeRenderer();
});
beforeEach(resetAll);

/** Local test forms only (never a real platform). */
const JOB = 'https://test-ats.local.example/memory/';
const page = (body: string) => `<!doctype html><html><body><h1>Vaga teste</h1><form action="/apply" method="post">
  <label for="nome">Nome completo *</label><input id="nome" name="nome" required>
  <label for="cv">Currículo (PDF) *</label><input id="cv" type="file" name="cv" accept=".pdf" required>
  ${body}
  <button type="submit">Enviar candidatura</button></form></body></html>`;
const HOW = (label: string) => `<label for="how">${label}</label><select id="how" name="how" required><option value="">Selecione</option><option>LinkedIn</option><option>Indicação</option></select>`;

const serve =
  (html: string): FixtureServer =>
  (url, method) =>
    url.startsWith(JOB) && method === 'GET' ? { body: html, contentType: 'text/html; charset=utf-8' } : null;

async function prepare(html: string, llm = applyLlm()) {
  const { app } = await seedApplyPersona(`${JOB}${Math.random().toString(36).slice(2)}`);
  const deps = { ...applyDeps(browser, [], { llm }), serve: serve(html) };
  const res = await runApply(deps, { applicationId: app.id, attempt: 1 }, { final: true });
  const answers = await db.formAnswer.findMany({ where: { applicationId: app.id } });
  return { res, answers };
}

async function memory(question: string, answer: string, fieldType: string, enabled = true) {
  return db.answerMemory.create({ data: { question, normalized: normalizeQuestion(question), answer, fieldType, evidence: [], approved: true, enabled, source: 'user', origin: 'needs_input' } });
}

describe('answer memory learning loop (US5, FR-020..FR-022)', { timeout: 120_000 }, () => {
  it('a confirmed memory answers the same question on another form and its use is counted', async () => {
    const m = await memory('Como soube da vaga?', 'LinkedIn', 'select');
    const { res, answers } = await prepare(page(HOW('Como soube da vaga? *')));
    expect(res.status, JSON.stringify(res.reasons)).toBe('ready');
    expect(answers.find((a) => a.fieldKey.includes('how'))).toMatchObject({ answer: 'LinkedIn', source: 'memória' });
    const after = await db.answerMemory.findUniqueOrThrow({ where: { id: m.id } });
    expect(after.usedCount).toBe(1);
    expect(after.lastUsedAt).not.toBeNull();
  });

  it('a disabled memory is not reused → the question is asked again', async () => {
    await memory('Como soube da vaga?', 'LinkedIn', 'select', false);
    const { res } = await prepare(page(HOW('Como soube da vaga? *')));
    expect(res.status).toBe('needs_input');
  });

  it('verified facts win over a conflicting memory; the conflict is recorded', async () => {
    await memory('Quantos anos de experiência com React?', '5', 'number');
    const { answers } = await prepare(page('<label for="yrs">Quantos anos de experiência com React? *</label><input id="yrs" type="number" name="yrs" required>'));
    const yrs = answers.find((a) => a.fieldKey.includes('yrs'))!;
    expect(yrs).toMatchObject({ answer: '2', source: 'calculado' });
    expect(yrs.findings).toEqual([{ sentenceIndex: 0, type: 'memory_conflict', token: '5' }]);
  });

  it('answers generated by the AI never become memories', async () => {
    const llm = applyLlm(() => ({ answers: [{ fieldId: 'f0', answer: 'Construir APIs com NestJS', factIds: ['f-exp1'], confidence: 0.9 }] }));
    await prepare(page('<label for="m">O que você mais gosta de fazer?</label><textarea id="m" name="m"></textarea>'), llm);
    expect(await db.answerMemory.count()).toBe(0);
  });
});
